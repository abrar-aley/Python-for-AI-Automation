# Basic Calclator

def add(num1,num2):
    return num1+num2

def subtract(num1,num2):
    return num1-num2

def divide(num1,num2):
    return num1/num2

def multiply(num1,num2):
    return num1*num2

print('Sum= ',add(5,2))
print('Difference= ',subtract(5,2))
print('Quotient= ',divide(5,2))
print('Product',multiply(5,2))


    